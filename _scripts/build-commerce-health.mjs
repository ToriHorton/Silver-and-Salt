#!/usr/bin/env node
// Commerce health feed for the CEO dashboard.
//
// Answers one question at a glance: can people actually buy a membership, and
// when did someone last do it?
//
// The 2026-09-22 outage ran for about 41 hours because nothing anywhere showed
// that number. Checkout was dead, the site looked perfect, and a failed quote
// writes no row and sends no email. The Worker cron and the deploy workflow now
// alert on the technical contract within minutes (src/checkout-probe.ts); this
// feed is the human-readable companion, so the dashboard can show a number that
// goes stale in an obvious way.
//
// Deliberately NOT an alert: at this volume a quiet day is normal, so a
// "no sales in 24h" alarm would cry wolf daily and get ignored. The tile
// informs; the canary alerts.
//
// Read-only. Writes one file into the private library repo's dashboard folder.
// Usage: node _scripts/build-commerce-health.mjs [--out <path>]

import { readFileSync, writeFileSync } from "node:fs";
import { initAdmin } from "@odla-ai/db";
import { execFileSync } from "node:child_process";

const OUT = (() => {
  const i = process.argv.indexOf("--out");
  if (i !== -1 && process.argv[i + 1]) return process.argv[i + 1];
  return `${process.env.HOME}/Projects/Silver-and-Salt-Library/dashboard/commerce-health.js`;
})();

const creds = JSON.parse(
  readFileSync(new URL("../.odla/credentials.local.json", import.meta.url), "utf8"),
);
if (!creds.envs?.prod?.dbKey) throw new Error("no cached production credentials; run provision --live first");
const db = initAdmin({
  appId: creds.envs.prod.tenantId,
  adminToken: creds.envs.prod.dbKey,
  endpoint: "https://db.odla.ai",
});

const ms = (row) => {
  const t = Date.parse(row?.$createdAt ?? "");
  return Number.isFinite(t) ? t : 0;
};
const latest = (rows) => rows.reduce((max, row) => Math.max(max, ms(row)), 0);
const iso = (t) => (t > 0 ? new Date(t).toISOString() : null);

const data = await db.query({
  applications: {},
  membershipQuoteProjections: {},
  subscriptionCheckoutIntents: {},
  stripeEventReceipts: {},
});

const apps = data.applications ?? [];
const intents = data.subscriptionCheckoutIntents ?? [];
const payments = (data.stripeEventReceipts ?? []).filter((r) => r.kind === "first_payment");

// The canary, over real HTTP, so the tile reports what an applicant would hit
// rather than what the database remembers.
let checkout = "unknown";
try {
  execFileSync(new URL("./verify-checkout-contract.sh", import.meta.url).pathname,
    ["https://silverandsaltcapital.com"], { stdio: "pipe" });
  checkout = "healthy";
} catch {
  checkout = "down";
}

let salesState = "unknown";
try {
  const res = await fetch("https://silverandsaltcapital.com/api/sales-state");
  salesState = String((await res.json()).state ?? "unknown");
} catch {
  // Left as unknown; the tile says so rather than guessing.
}

const feed = {
  generated: new Date().toISOString(),
  checkout,
  salesState,
  lastQuoteAt: iso(latest(data.membershipQuoteProjections ?? [])),
  lastCheckoutAt: iso(latest(intents)),
  lastPaymentAt: iso(latest(payments)),
  awaitingPayment: apps.filter((a) => a.status === "submitted" && !a.stripeSubscriptionId).length,
  paidMembers: apps.filter((a) => a.stripeSubscriptionId).length,
};

writeFileSync(
  OUT,
  `// Silver & Salt Capital, commerce health for the dashboard. Generated by\n` +
    `// _scripts/build-commerce-health.mjs in the website repo. Do not hand-edit.\n` +
    `window.SSC_COMMERCE_HEALTH = ${JSON.stringify(feed, null, 2)};\n`,
);
console.log(`wrote ${OUT}`);
console.log(JSON.stringify(feed, null, 2));
